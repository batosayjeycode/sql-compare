import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import type { Plugin, ResolvedConfig } from 'vite';

/**
 * Offline support (NFR Privacy: works with the network disabled after the
 * first load). After the build, writes `sw.js` with the list of files to
 * precache: the app shell, both workers, the parsers (including the
 * PostgreSQL WASM) and the Latin font files. Other font subsets are cached
 * the first time a page needs them.
 *
 * Also adds the production Content-Security-Policy as a <meta> tag (the dev
 * server needs inline scripts, so it is build-only). Hosts that support
 * headers (Cloudflare Pages: public/_headers) send the same policy.
 */

export const CONTENT_SECURITY_POLICY = [
  "default-src 'self'",
  // The PostgreSQL parser is WebAssembly.
  "script-src 'self' 'wasm-unsafe-eval'",
  // CodeMirror injects its theme as <style> elements.
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "connect-src 'self'",
  "worker-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
].join('; ');

/** Preloaded font files: the Latin subsets of both UI fonts. */
const PRELOADED_FONT = /(inter|jetbrains-mono)-latin-wght-normal-[\w-]+\.woff2$/;

/** Precached font files: Latin subsets only (others load on demand). */
const PRECACHED_FONT = /(latin|latin-ext)-wght-normal-[\w-]+\.woff2$/;

async function files(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await files(path)));
    else out.push(path);
  }
  return out;
}

function precacheable(path: string): boolean {
  if (path.endsWith('.map') || path === 'sw.js' || path === '_headers') return false;
  if (path.endsWith('.woff2') || path.endsWith('.woff')) return PRECACHED_FONT.test(path);
  return true;
}

const serviceWorker = (
  version: string,
  precache: string[],
) => `// Generated by vite.pwa.ts. Do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = 'sql-compare-' + VERSION;
const RUNTIME = 'sql-compare-runtime';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((k) => k.startsWith('sql-compare-') && k !== CACHE && k !== RUNTIME)
            .map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;

  // Pages: the network when available (fresh deploys), else the cached shell.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(() =>
        caches
          .match('/index.html', { cacheName: CACHE, ignoreVary: true })
          .then((r) => r || Response.error()),
      ),
    );
    return;
  }

  // Hashed assets never change: cache first; anything else is cached once fetched.
  event.respondWith(
    // ignoreVary: module scripts send Origin, the precache requests didn't.
    caches.match(request, { ignoreVary: true }).then(
      (cached) =>
        cached ||
        fetch(request).then((response) => {
          if (response.ok && response.type === 'basic') {
            const copy = response.clone();
            caches.open(RUNTIME).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;

export function pwa(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'sql-compare:pwa',
    apply: 'build',
    configResolved(resolved) {
      config = resolved;
    },
    transformIndexHtml: {
      order: 'post',
      handler: (_html, ctx) => [
        {
          tag: 'meta',
          attrs: { 'http-equiv': 'Content-Security-Policy', content: CONTENT_SECURITY_POLICY },
          injectTo: 'head-prepend',
        },
        // The UI fonts load with the page, before the app renders: no shift when they swap in.
        ...Object.keys(ctx.bundle ?? {})
          .filter((f) => PRELOADED_FONT.test(f))
          .map((f) => ({
            tag: 'link',
            attrs: {
              rel: 'preload',
              href: `/${f}`,
              as: 'font',
              type: 'font/woff2',
              crossorigin: '',
            },
            injectTo: 'head' as const,
          })),
      ],
    },
    async closeBundle() {
      const outDir = join(config.root, config.build.outDir);
      const all = (await files(outDir)).map((f) => relative(outDir, f).split('\\').join('/'));
      const precache = all
        .filter(precacheable)
        .map((f) => (f === 'index.html' ? '/index.html' : `/${f}`));
      precache.sort();
      const hash = createHash('sha256');
      for (const f of precache) {
        hash.update(f);
        hash.update(await readFile(join(outDir, f.slice(1))));
      }
      const version = hash.digest('hex').slice(0, 12);
      await writeFile(join(outDir, 'sw.js'), serviceWorker(version, ['/', ...precache]));
    },
  };
}
